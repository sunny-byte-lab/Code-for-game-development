"""N.E.X.U.S. Google Gemini AI Provider.
Direct integration using standard HTTP REST API (urllib) with zero extra dependencies.
"""

import json
import logging
import urllib.request
import urllib.error
from typing import List, Optional, Iterator
from nexus_ai.provider_base import AIProvider, ChatMessage, AIResponse

logger = logging.getLogger("NEXUS.AI.Gemini")


class GeminiProvider(AIProvider):
    """Google Gemini AI integration via Gemini REST API."""

    def __init__(self, api_key: str = "", model_name: str = "gemini-1.5-flash"):
        self.api_key = api_key
        self.model_name = model_name
        self.endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model_name}:generateContent"

    @property
    def name(self) -> str:
        return "gemini"

    @property
    def is_configured(self) -> bool:
        return bool(self.api_key and len(self.api_key) > 10)

    def generate(self, messages: List[ChatMessage], system_prompt: Optional[str] = None) -> AIResponse:
        if not self.is_configured:
            return AIResponse(
                content="[AI Error] Gemini API key is not configured in N.E.X.U.S. settings.",
                model=self.model_name,
                error="API_KEY_MISSING"
            )

        payload = self._build_gemini_payload(messages, system_prompt)
        url = f"{self.endpoint}?key={self.api_key}"
        req_data = json.dumps(payload).encode("utf-8")

        req = urllib.request.Request(
            url,
            data=req_data,
            headers={"Content-Type": "application/json"}
        )

        try:
            with urllib.request.urlopen(req, timeout=15) as resp:
                resp_json = json.loads(resp.read().decode("utf-8"))
            
            candidates = resp_json.get("candidates", [])
            if not candidates:
                return AIResponse(content="[No response generated by Gemini]", model=self.model_name)
            
            parts = candidates[0].get("content", {}).get("parts", [])
            text_out = "".join(p.get("text", "") for p in parts)
            usage = resp_json.get("usageMetadata", {})
            return AIResponse(
                content=text_out,
                model=self.model_name,
                usage={"prompt_tokens": usage.get("promptTokenCount", 0), "total_tokens": usage.get("totalTokenCount", 0)}
            )
        except urllib.error.HTTPError as e:
            err_body = e.read().decode("utf-8", errors="replace")
            logger.error(f"Gemini API HTTP {e.code}: {err_body}")
            return AIResponse(content=f"[Gemini API Error {e.code}]", model=self.model_name, error=str(e))
        except Exception as e:
            logger.error(f"Gemini request failed: {e}")
            return AIResponse(content=f"[Connection Error: {e}]", model=self.model_name, error=str(e))

    def stream(self, messages: List[ChatMessage], system_prompt: Optional[str] = None) -> Iterator[str]:
        # Fallback to single generation chunking for standard REST
        resp = self.generate(messages, system_prompt)
        if resp.content:
            yield resp.content

    def _build_gemini_payload(self, messages: List[ChatMessage], system_prompt: Optional[str]) -> dict:
        contents = []
        for m in messages:
            role = "user" if m.role == "user" else "model"
            contents.append({"role": role, "parts": [{"text": m.content}]})

        payload = {"contents": contents}
        if system_prompt:
            payload["systemInstruction"] = {"parts": [{"text": system_prompt}]}
        return payload
